#!/usr/bin/env python3
"""Inject nanopb .options constraints as inline field options into a .proto file.

The nanopb .options file format is specific to the nanopb C generator and is
ignored by standard protoc (including --python_out). By injecting the options
directly into the proto file's field declarations, protoc will embed them in
the serialized descriptor, making them accessible in Python via:

    from meshtastic.protobuf import mesh_pb2, nanopb_pb2
    field = mesh_pb2.DESCRIPTOR.message_types_by_name['User'].fields_by_name['long_name']
    opts = field.GetOptions().Extensions[nanopb_pb2.nanopb]
    print(opts.max_size)  # 40

Usage:
    inject_nanopb_options.py <options_file> <proto_file>

The proto_file is modified in-place. Intended to operate on temporary copies
generated by regen-protobufs.sh, not the source .proto files.
"""

import re
import sys
from pathlib import Path
from typing import Any

# IntSize enum values from nanopb.proto
INT_SIZE_ENUM = {8: "IS_8", 16: "IS_16", 32: "IS_32", 64: "IS_64"}

# Options that are valid proto FieldOptions and useful outside of C code generation.
# We skip C-only options (anonymous_oneof, no_unions, skip_message, packed_struct,
# packed_enum, mangle_names, callback_datatype, callback_function, descriptorsize,
# type, type_override) since they either don't apply to proto fields or are C-specific.
FIELD_OPTIONS = frozenset(
    {
        "max_size",
        "max_length",
        "max_count",
        "int_size",
        "fixed_length",
        "fixed_count",
        "long_names",
        "proto3",
        "default_has",
        "sort_by_tag",
        "msgid",
    }
)


def parse_value(s: str) -> Any:
    """Convert an option value string to an appropriate Python type."""
    if re.fullmatch(r"-?[0-9]+", s):
        return int(s)
    if s.lower() == "true":
        return True
    if s.lower() == "false":
        return False
    return s


def parse_options_file(
    path: Path,
) -> tuple[dict[tuple[str, ...], dict[str, Any]], dict[str, dict[str, Any]]]:
    """Parse a nanopb .options file.

    Returns
    -------
        specific: maps (message_path..., field_name) -> {option: value}
                   e.g. ('User', 'long_name') or ('Route', 'Link', 'uid')
        wildcard: maps field_name -> {option: value}
                   applies to any field with this name in the same proto file
    """
    specific: dict[tuple[str, ...], dict[str, Any]] = {}
    wildcard: dict[str, dict[str, Any]] = {}

    with open(path, encoding="utf-8") as f:
        for line in f:
            # Strip inline comments
            comment_pos = line.find("#")
            if comment_pos >= 0:
                line = line[:comment_pos]
            line = line.strip().lstrip("*").strip()
            if not line:
                continue

            tokens = line.split()
            if len(tokens) < 2:
                continue

            pattern = tokens[0]
            opts: dict[str, Any] = {}
            for tok in tokens[1:]:
                if ":" in tok:
                    k, v = tok.split(":", 1)
                    if k in FIELD_OPTIONS:
                        opts[k] = parse_value(v)

            if not opts:
                continue

            if "." in pattern:
                # e.g. "User.long_name" -> key=('User', 'long_name')
                # or "Route.Link.uid"   -> key=('Route', 'Link', 'uid')
                parts = tuple(pattern.split("."))
                if parts in specific:
                    specific[parts].update(opts)
                else:
                    specific[parts] = opts
            else:
                # wildcard: applies to any field with this name
                if pattern in wildcard:
                    wildcard[pattern].update(opts)
                else:
                    wildcard[pattern] = opts

    return specific, wildcard


def format_nanopb_opts(opts: dict[str, Any]) -> str:
    """Format a dict of nanopb options as a proto field options annotation string."""
    parts = []
    for k in sorted(opts.keys()):
        v = opts[k]
        if k == "int_size":
            enum_val = INT_SIZE_ENUM.get(v, f"IS_{v}")
            parts.append(f"(nanopb).int_size = {enum_val}")
        elif isinstance(v, bool):
            parts.append(f"(nanopb).{k} = {'true' if v else 'false'}")
        else:
            parts.append(f"(nanopb).{k} = {v}")
    return ", ".join(parts)


def message_path_matches(
    context_stack: list[tuple[str, str]], msg_path: tuple[str, ...]
) -> bool:
    """Check if the current message context ends with msg_path.

    context_stack entries are ('message'|'oneof'|'enum', name).
    msg_path is the tuple of message names from the options pattern,
    e.g. ('User',) or ('Route', 'Link').
    """
    msg_names = [name for kind, name in context_stack if kind == "message"]
    n = len(msg_path)
    return len(msg_names) >= n and tuple(msg_names[-n:]) == msg_path


def _collect_field_options(
    fname: str,
    context_stack: list[tuple[str, str]],
    specific: dict[tuple[str, ...], dict[str, Any]],
    wildcard: dict[str, dict[str, Any]],
    applied_specific: set[tuple[str, ...]] | None,
    applied_wildcard: set[str] | None,
) -> dict[str, Any]:
    """Collect the nanopb options that apply to one field, recording matches."""
    # Wildcard < specific: more-specific paths override less-specific ones
    extra: dict[str, Any] = {}

    # 1. Wildcard: any field with this name in this proto file
    if fname in wildcard:
        extra.update(wildcard[fname])
        if applied_wildcard is not None:
            applied_wildcard.add(fname)

    # 2. Specific: merge ALL matching keys, shortest path first,
    matching_specific = sorted(
        (
            (key, opts)
            for key, opts in specific.items()
            if key[-1] == fname and message_path_matches(context_stack, key[:-1])
        ),
        key=lambda item: len(item[0]),
    )
    for key, opts in matching_specific:
        extra.update(opts)
        if applied_specific is not None:
            applied_specific.add(key)

    return extra


def inject_into_proto(
    content: str,
    specific: dict[tuple[str, ...], dict[str, Any]],
    wildcard: dict[str, dict[str, Any]],
    nanopb_import_path: str,
    *,
    applied_specific: set[tuple[str, ...]] | None = None,
    applied_wildcard: set[str] | None = None,
) -> str:
    """Inject nanopb field options into a proto file's text content.

    Adds an import for nanopb.proto if not already present.
    Returns the modified content.

    When ``applied_specific``/``applied_wildcard`` sets are provided they are
    filled with the option keys that actually triggered a rewrite, so callers
    can detect constraints that no longer match any field.
    """
    if not specific and not wildcard:
        return content

    lines = content.split("\n")

    # Check if nanopb is already imported (after namespace fixup, it will be
    # 'meshtastic/protobuf/nanopb.proto')
    nanopb_already_imported = any(
        "nanopb.proto" in line for line in lines if line.strip().startswith("import")
    )

    # Track the index of the last import line so we can insert after it
    last_import_idx = max(
        (
            i
            for i, line in enumerate(lines)
            if line.strip().startswith("import ") and ";" in line
        ),
        default=-1,
    )

    # State
    context_stack: list[tuple[str, str]] = []  # ('message'|'oneof'|'enum', name)
    result: list[str] = []
    import_added = nanopb_already_imported
    # Formatted nanopb options awaiting the closing line of a multi-line
    # field option block.
    pending_nanopb: str | None = None
    # Open "[...]" option-block depth across lines; while positive, lines are
    # annotation/option content and must not affect structural tracking.
    options_depth = 0

    # Patterns for proto structural elements
    message_re = re.compile(r"^(\s*)message\s+(\w+)\s*\{")
    oneof_re = re.compile(r"^(\s*)oneof\s+(\w+)\s*\{")
    enum_re = re.compile(r"^(\s*)enum\s+(\w+)\s*\{")
    close_re = re.compile(r"^\s*\}\s*$")

    # Pattern for field declarations:
    #   indent  [optional|repeated]  type  name  =  number  [options]  ;
    # We exclude map<> fields (different syntax, nanopb handles them differently)
    # and enum value lines (no type keyword before the name).
    field_re = re.compile(
        r"^(\s*)"  # (1) indent
        r"(optional\s+|repeated\s+)?"  # (2) optional qualifier
        r"([\w.]+)\s+"  # (3) field type (possibly qualified like google.protobuf.Any)
        r"(\w+)\s*"  # (4) field name
        r"=\s*(\d+)"  # (5) field number
        r"(?:\s*\[([^\]]*)\])?"  # (6) existing options, without brackets
        r"\s*;"  # trailing semicolon
    )

    # Same prefix, for fields whose option block is not closed on this line
    # (e.g. "uint32 x = 1 [(meshtastic.field_metadata) = {"). The declaration
    # continues over multiple lines, so the rewrite is completed on the line
    # that closes the option block instead of here.
    field_open_re = re.compile(
        r"^(\s*)"
        r"(optional\s+|repeated\s+)?"
        r"([\w.]+)\s+"
        r"(\w+)\s*"
        r"=\s*(\d+)"
        r"\s*\["
    )

    # String literals and comments must not contribute brackets.
    def _code_part(text: str, in_block: bool) -> tuple[str, bool]:
        out: list[str] = []
        s = text
        while s:
            if in_block:
                end = s.find("*/")
                if end < 0:
                    return "".join(out), True
                s = s[end + 2 :]
                in_block = False
                continue
            markers = [
                (i, t)
                for i, t in (
                    (s.find("/*"), "/*"),
                    (s.find("//"), "//"),
                    (s.find('"'), '"'),
                )
                if i >= 0
            ]
            if not markers:
                out.append(s)
                return "".join(out), in_block
            i, t = min(markers)
            if t == '"':
                j = i + 1
                while j < len(s):
                    if s[j] == "\\":
                        j += 2
                        continue
                    if s[j] == '"':
                        break
                    j += 1
                out.append(s[:i])
                out.append('""')
                s = s[min(j + 1, len(s)) :]
            elif t == "/*":
                out.append(s[:i])
                in_block = True
                s = s[i + 2 :]
            else:  # line comment
                out.append(s[:i])
                return "".join(out), in_block
        return "".join(out), in_block

    in_block_comment = False

    for i, line in enumerate(lines):
        # Insert nanopb import right after the last existing import line.
        # Only do this when there IS an existing import (last_import_idx >= 0);
        # if there are no imports we fall through to the syntax-line fallback below.
        if not import_added and last_import_idx >= 0 and i == last_import_idx + 1:
            result.append(f'import "{nanopb_import_path}";')
            import_added = True

        code, in_block_comment = _code_part(line, in_block_comment)
        line_opens = code.count("[")
        line_closes = code.count("]")
        in_options = options_depth > 0

        # Complete a pending multi-line field rewrite on the line that closes
        # its option block: insert the nanopb options before the final "]".
        closes_block = in_options and options_depth + line_opens - line_closes == 0
        if pending_nanopb is not None and closes_block and "]" in code and ";" in code:
            head, _, tail = line.rpartition("]")
            result.append(f"{head}, {pending_nanopb}]{tail}")
            pending_nanopb = None
            options_depth += line_opens - line_closes
            continue

        if not in_options:
            # --- Track message/oneof/enum nesting ---
            m = message_re.match(line)
            if m:
                context_stack.append(("message", m.group(2)))
                result.append(line)
                options_depth += line_opens - line_closes
                continue

            m = oneof_re.match(line)
            if m:
                context_stack.append(("oneof", m.group(2)))
                result.append(line)
                options_depth += line_opens - line_closes
                continue

            m = enum_re.match(line)
            if m:
                context_stack.append(("enum", m.group(2)))
                result.append(line)
                options_depth += line_opens - line_closes
                continue

            if close_re.match(line) and context_stack:
                context_stack.pop()
                result.append(line)
                options_depth += line_opens - line_closes
                continue

            # Skip field injection inside enum bodies (enum values look like
            # fields but should not have nanopb options added)
            in_enum = bool(context_stack) and context_stack[-1][0] == "enum"

            # --- Try to match and modify a field declaration ---
            m = field_re.match(line)
            if m and not in_enum:
                existing_opts = m.group(6) or ""
                extra = _collect_field_options(
                    m.group(4),
                    context_stack,
                    specific,
                    wildcard,
                    applied_specific,
                    applied_wildcard,
                )

                if extra:
                    nanopb_str = format_nanopb_opts(extra)
                    if existing_opts.strip():
                        opts_block = f"[{existing_opts}, {nanopb_str}]"
                    else:
                        opts_block = f"[{nanopb_str}]"
                    qual = (m.group(2) or "").rstrip()
                    sep = " " if qual else ""
                    line = (
                        f"{m.group(1)}{qual}{sep}{m.group(3)} "
                        f"{m.group(4)} = {m.group(5)} {opts_block};"
                    )
            elif not in_enum:
                # Field whose option block continues on later lines: remember
                # the injected options until the block closes.
                m_open = field_open_re.match(line)
                if m_open and line_opens > line_closes:
                    extra = _collect_field_options(
                        m_open.group(4),
                        context_stack,
                        specific,
                        wildcard,
                        applied_specific,
                        applied_wildcard,
                    )
                    if extra:
                        pending_nanopb = format_nanopb_opts(extra)

        result.append(line)
        options_depth += line_opens - line_closes

    # Edge case: if there were no import lines, add nanopb import after syntax line
    if not import_added:
        for i, line in enumerate(result):
            if line.strip().startswith("syntax") and line.strip().endswith(";"):
                result.insert(i + 1, f'import "{nanopb_import_path}";')
                break

    return "\n".join(result)


# Options entries that matched no field even in the last known-good binding
# regeneration. They are stale upstream (fields removed, or paths naming a
# field instead of its message type) and are reported as warnings instead of
# failing the build. Anything else that stops matching fails loudly.
KNOWN_UNMATCHED = frozenset(
    {
        ("MyNodeInfo", "air_period_rx"),
        ("MyNodeInfo", "air_period_tx"),
        ("MyNodeInfo", "firmware_version"),
        ("MeshBeacon", "offer_channel", "name"),
        ("MeshBeacon", "offer_channel", "psk"),
        ("MeshBeaconConfig", "broadcast_offer_channel", "name"),
        ("MeshBeaconConfig", "broadcast_offer_channel", "psk"),
    }
)


def main() -> int:
    """CLI entry point: inject nanopb options into a proto file."""
    if len(sys.argv) != 3:
        print(
            f"Usage: {sys.argv[0]} <options_file> <proto_file>",
            file=sys.stderr,
        )
        return 1

    opts_path = Path(sys.argv[1])
    proto_path = Path(sys.argv[2])

    if not opts_path.exists():
        print(f"Options file not found: {opts_path}", file=sys.stderr)
        return 1

    if not proto_path.exists():
        print(f"Proto file not found: {proto_path}", file=sys.stderr)
        return 1

    specific, wildcard = parse_options_file(opts_path)
    total = len(specific) + len(wildcard)

    if total == 0:
        print(f"  [{opts_path.name}] No injectable options found, skipping.")
        return 0

    content = proto_path.read_text(encoding="utf-8")

    # After regen-protobufs.sh's namespace fixup, the nanopb import path is:
    nanopb_import_path = "meshtastic/protobuf/nanopb.proto"

    applied_specific: set[tuple[str, ...]] = set()
    applied_wildcard: set[str] = set()
    modified = inject_into_proto(
        content,
        specific,
        wildcard,
        nanopb_import_path,
        applied_specific=applied_specific,
        applied_wildcard=applied_wildcard,
    )
    proto_path.write_text(modified, encoding="utf-8")

    # A constraint that matched no field means either the schema moved or the
    # injector could not parse the field declaration; fail loudly either way so
    # silent wire-contract loss cannot ship.
    missing_specific = sorted(set(specific) - applied_specific)
    missing_wildcard = sorted(set(wildcard) - applied_wildcard)
    failed = False
    for key in missing_specific:
        if key in KNOWN_UNMATCHED:
            print(
                f"  [{opts_path.name}] WARNING: no field matched "
                f"'{'.'.join(key)}' (known-unmatched stale upstream entry)"
            )
            continue
        print(
            f"  [{opts_path.name}] ERROR: no field matched '{'.'.join(key)}'",
            file=sys.stderr,
        )
        failed = True
    for name in missing_wildcard:
        print(
            f"  [{opts_path.name}] ERROR: no field matched '*.{name}'",
            file=sys.stderr,
        )
        failed = True
    if failed:
        return 1

    print(
        f"  [{opts_path.name}] Injected {len(specific)} specific + "
        f"{len(wildcard)} wildcard option(s) into {proto_path.name}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
